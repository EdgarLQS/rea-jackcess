namespace {

using rea_jackcess::BlobValue;
using rea_jackcess::Database;
using rea_jackcess::Row;
using rea_jackcess::RowCursor;
using rea_jackcess::Table;
using rea_jackcess::Value;

void check(bool condition, const std::string& message) {
    if (!condition) {
        throw std::runtime_error(message);
    }
}

std::string read_bytes(const std::filesystem::path& path) {
    std::ifstream input(path, std::ios::binary);
    check(static_cast<bool>(input), "could not read the Jet4 index fixture");
    return {std::istreambuf_iterator<char>(input), std::istreambuf_iterator<char>()};
}

Table get_table(const Database& database, const std::string& name) {
    const auto tables = database.tables();
    const auto found = std::find_if(tables.begin(), tables.end(), [&](const auto& table) {
        return table.name() == name;
    });
    check(found != tables.end(), "fixture table is missing: " + name);
    return *found;
}

std::int32_t id_of(const Row& row) {
    const auto* id = std::get_if<std::int32_t>(&row.at(0));
    check(id != nullptr, "Id is always a LONG");
    return *id;
}

std::vector<std::int32_t> collect(RowCursor cursor) {
    std::vector<std::int32_t> ids;
    while (auto row = cursor.next()) {
        ids.push_back(id_of(*row));
    }
    return ids;
}

std::string label(const std::vector<std::int32_t>& ids) {
    std::string text;
    for (const auto id : ids) {
        if (!text.empty()) {
            text += ',';
        }
        text += std::to_string(id);
    }
    return text;
}

void check_ids(const std::vector<std::int32_t>& actual, const std::vector<std::int32_t>& expected,
               const std::string& scan) {
    check(actual == expected, scan + ": expected [" + label(expected) + "], got [" + label(actual) + "]");
}

// The fixture is generated by tools/validation/JackcessJet4IndexFixture.java, and the fixed JAR
// index cursor returns the same nine entries in this order: NULL sorts first in both key
// positions, then AS/A, then the EU block with a NULL code ahead of "A", and "A" ahead of "AA".
void check_schema(const Table& table) {
    const auto& columns = table.columns();
    check(columns.size() == 5, "unexpected column count");
    check(columns[1].name == "Region" && columns[1].type == rea_jackcess::DataType::text &&
              columns[1].size == 16,
          "Region must be a 8-unit TEXT column");
    check(columns[2].name == "Code" && columns[2].type == rea_jackcess::DataType::text &&
              columns[2].size == 16,
          "Code must be a 8-unit TEXT column");

    const auto& indexes = table.indexes();
    check(indexes.size() == 2, "unexpected index count");
    const auto& key = indexes[1];
    check(key.name == "RegionCodeKey", "unexpected composite index name");
    check(key.unique, "the composite index must be unique");
    check(key.ignore_nulls, "the composite index must carry ignore-nulls");
    check(!key.primary_key && !key.foreign_key, "the composite index is neither key kind");
    check(key.columns.size() == 2 && key.columns[0].name == "Region" && key.columns[0].ascending &&
              key.columns[1].name == "Code" && key.columns[1].ascending,
          "unexpected composite index columns");
    check(key.unique_entry_count == 9, "unexpected composite index entry count");
}

void check_long_values(Table table) {
    const auto rows = collect(table.rows());
    check(rows == std::vector<std::int32_t>{1}, "LongValues must hold one row");
    auto cursor = table.rows();
    const auto row = cursor.next();
    check(row.has_value(), "LongValues row is missing");
    const auto* ole = std::get_if<BlobValue>(&row->at(1));
    check(ole != nullptr, "OleVal must decode as a blob");
    check(ole->bytes.size() == 9000, "OleVal must keep the full 9000-byte payload");
    for (std::size_t index = 0; index < ole->bytes.size(); ++index) {
        const auto expected = static_cast<std::uint8_t>((0x40 + index) & 0xffu);
        check(ole->bytes[index] == expected, "OleVal payload differs at byte " + std::to_string(index));
    }
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::cerr << "usage: jet4_index_read <fixture.mdb>\n";
        return 2;
    }
    const std::filesystem::path fixture(argv[1]);
    if (!std::filesystem::exists(fixture)) {
        // Generated on demand by tools/validation; never committed. CTest maps 77 to skipped.
        std::cout << "Jet4 index fixture is missing, run the generator first: " << fixture << '\n';
        return 77;
    }
    try {
        const std::string before = read_bytes(fixture);
        {
            Database database = Database::open(fixture);
            Table table = get_table(database, "RegionCode");
            check_schema(table);
            check(table.row_count_header() == 9, "unexpected row count header");

            // The sequential scan keeps the insertion order and includes the NULL-key rows.
            check_ids(collect(table.rows()), {1, 2, 3, 4, 5, 6, 7, 9, 10}, "sequential scan");

            check_ids(collect(table.rows_by_index("RegionCodeKey")),
                      {6, 4, 7, 1, 10, 2, 5, 3, 9}, "composite index scan");
            check_ids(collect(table.rows_by_index_reverse("RegionCodeKey")),
                      {9, 3, 5, 2, 10, 1, 7, 4, 6}, "composite index reverse scan");

            // A prefix on the leading column walks the whole EU block, including the NULL code.
            check_ids(collect(table.rows_by_index_prefix("RegionCodeKey", {std::string("EU")})),
                      {7, 1, 10, 2, 5}, "prefix scan over EU");
            check_ids(collect(table.rows_by_index_prefix("RegionCodeKey", {std::string("EU")}, true)),
                      {5, 2, 10, 1, 7}, "reverse prefix scan over EU");

            // [EU/A, US/A) stops before the US block.
            check_ids(collect(table.rows_by_index_range("RegionCodeKey",
                                                        std::vector<Value>{std::string("EU"), std::string("A")},
                                                        std::vector<Value>{std::string("US"), std::string("A")})),
                      {1, 10, 2, 5}, "composite range scan");

            const auto found = table.find_row_by_index(
                "RegionCodeKey", std::vector<Value>{std::string("EU"), std::string("AA")});
            check(found.has_value(), "composite lookup missed EU/AA");
            check(id_of(*found) == 10, "composite lookup returned the wrong row");
            check(std::get_if<std::string>(&found->at(1)) != nullptr &&
                      *std::get_if<std::string>(&found->at(1)) == "EU",
                  "composite lookup returned the wrong Region");

            Table long_values = get_table(database, "LongValues");
            check_long_values(long_values);
        }
        check(read_bytes(fixture) == before, "a read-only open modified the fixture");
        std::cout << "Jet4 composite index read checks passed: " << fixture.filename().string() << '\n';
        return 0;
    } catch (const std::exception& error) {
        std::cerr << "Jet4 index read check failed: " << error.what() << '\n';
        return 1;
    }
}
